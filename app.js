function field(id, label, type, placeholder, extra = "") {
  return `
    <div class="field" id="wrap-${id}">
      <label for="${id}">${label}</label>
      <input class="input" id="${id}" type="${type}" placeholder="${placeholder}" value="${extra}" />
      <div class="error">${t().required}</div>
    </div>`;
}

function render() {
  const copy = t();
  document.documentElement.lang = state.lang;
  document.documentElement.dir = state.lang === "ar" ? "rtl" : "ltr";
  document.body.dir = document.documentElement.dir;
  document.getElementById("langBtn").textContent = copy.langToggle;
  document.getElementById("pageTitle").textContent = copy.title;
  document.getElementById("reqTitleText").textContent = copy.reqTitle;
  document.getElementById("reqList").innerHTML = copy.reqs.map((r) => `<li>${r}</li>`).join("");
  document.getElementById("footerText").textContent = copy.footer;

  document.getElementById("reqBox").hidden = state.step !== 1;
  const checkSvg =
    '<svg viewBox="0 0 24 24" width="14" height="14" fill="none" aria-hidden="true"><path d="M5 12.5l5 5L20 7" stroke="#fff" stroke-width="2.6" stroke-linecap="round" stroke-linejoin="round"/></svg>';
  const stepper = document.getElementById("stepper");
  stepper.innerHTML = copy.steps
    .map((label, i) => {
      const n = i + 1;
      const cls = n < state.step ? "is-done" : n === state.step ? "is-active" : "";
      const lineCls = n < state.step ? "is-done" : "";
      const line = n < 4 ? `<div class="step-line ${lineCls}" aria-hidden="true"></div>` : "";
      const num = n < state.step ? checkSvg : String(n);
      return `<div class="step ${cls}"><div class="step-num">${num}</div><p class="step-label">${label}</p></div>${line}`;
    })
    .join("");

  const root = document.getElementById("formRoot");
  if (state.step === 5) {
    root.innerHTML = `
      <div class="card success">
        <svg width="56" height="56" viewBox="0 0 24 24" fill="none"><circle cx="12" cy="12" r="12" fill="#e8f7ee"/><path d="M7 12.5l3 3 7-7" stroke="#157347" stroke-width="2" fill="none"/></svg>
        <h2>${copy.successTitle}</h2>
        <p>${copy.successBody}</p>
        <p>${copy.successTime}</p>
      </div>`;
    return;
  }

  if (state.step === 1) root.innerHTML = stepApplicant(copy);
  if (state.step === 2) root.innerHTML = stepBusiness(copy);
  if (state.step === 3) root.innerHTML = stepOwners(copy);
  if (state.step === 4) root.innerHTML = stepReview(copy);
  bindStep();
}

